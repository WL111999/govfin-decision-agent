def build_seed_ontology() -> Ontology:
    classes = [
        OwlClass(
            name=name,
            parent=parent,
            layer=layer,
            definition=definition,
            aliases=list(aliases),
            required_properties=list(required),
            optional_properties=list(optional),
        )
        for name, parent, layer, definition, aliases, required, optional in _CLASS_SPECS
    ]

    properties: list[OwlProperty] = []
    for name, domain, rng, definition, inverse, functional, min_c, max_c in _OBJECT_PROPS:
        properties.append(
            OwlProperty(
                name=name,
                domain=domain,
                range=rng,
                kind="object",
                definition=definition,
                inverse=inverse,
                functional=functional,
                min_cardinality=min_c,
                max_cardinality=max_c,
            )
        )
    for name, domain, rdfs_range, definition, min_c, max_c in _DATATYPE_PROPS:
        properties.append(
            OwlProperty(
                name=name,
                domain=domain,
                range=rdfs_range,
                kind="datatype",
                definition=definition,
                rdfs_range=rdfs_range,
                min_cardinality=min_c,
                max_cardinality=max_c,
            )
        )

    ont = Ontology(
        version="0.1.0",
        classes=classes,
        properties=properties,
        provenance={
            "name": "GovFin 跨域信贷决策本体",
            "description": "覆盖金融授信与政务数据两大域，支撑跨文档多跳推理与决策溯源",
            "seed_class_count": len(classes),
            "seed_property_count": len(properties),
        },
    )

    # 显式互斥公理：这些组合在业务上不可能同时成立
    ont.classes["企业"].disjoint_with.append("自然人")
    ont.classes["自然人"].disjoint_with.append("企业")
    ont.classes["采纳路径"].disjoint_with.append("被拒路径")
    ont.classes["被拒路径"].disjoint_with.append("采纳路径")
    ont._validate_axioms()
    return ont


